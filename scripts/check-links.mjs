// Checks every internal link and anchor in the static export (out/) so a
// broken link fails CI before it can reach master (which deploys straight to
// Netlify). Run after `npm run build`: `node scripts/check-links.mjs`.
// No dependencies: it reads the exported HTML with regexes, which is enough
// for the markup Next generates.
import fs from "node:fs";
import path from "node:path";

const OUT = path.join(process.cwd(), "out");

if (!fs.existsSync(OUT)) {
  console.error("check-links: out/ not found, run `npm run build` first");
  process.exit(1);
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(OUT);
const htmlFiles = files.filter((f) => f.endsWith(".html"));

// Sources of Netlify redirects (public/_redirects): linking to one is allowed.
const redirectSources = new Set();
const redirectsFile = path.join(OUT, "_redirects");
if (fs.existsSync(redirectsFile)) {
  for (const line of fs.readFileSync(redirectsFile, "utf8").split("\n")) {
    const from = line.trim().split(/\s+/)[0];
    if (from && !from.startsWith("#")) redirectSources.add(from);
  }
}

/** The exported file a site path is served from (trailingSlash: false), or null. */
function resolve(urlPath) {
  const decoded = decodeURIComponent(urlPath);
  if (decoded === "/") return path.join(OUT, "index.html");
  const base = path.join(OUT, decoded);
  for (const candidate of [base, `${base}.html`, path.join(base, "index.html")]) {
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  return null;
}

const idCache = new Map();
function idsOf(file) {
  if (!idCache.has(file)) {
    const html = fs.readFileSync(file, "utf8");
    idCache.set(file, new Set([...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])));
  }
  return idCache.get(file);
}

const problems = [];
let checked = 0;

for (const file of htmlFiles) {
  const page = "/" + path.relative(OUT, file).replace(/\\/g, "/").replace(/(index)?\.html$/, "");
  const html = fs.readFileSync(file, "utf8");
  for (const [, attr, raw] of html.matchAll(/\s(href|src)="([^"]*)"/g)) {
    const url = raw.replace(/&amp;/g, "&");
    // Only internal links: root-relative paths and same-page anchors.
    if (!(url.startsWith("/") || url.startsWith("#")) || url.startsWith("//")) continue;
    if (url.startsWith("/_next/")) continue; // build assets, generated by Next itself
    checked++;

    const [beforeHash, hash] = url.split("#");
    const urlPath = beforeHash.split("?")[0];
    const target = urlPath ? resolve(urlPath) : file;

    if (!target) {
      if (!redirectSources.has(urlPath)) problems.push(`${page}: ${attr}="${url}" → no such page or file`);
      continue;
    }
    if (hash && target.endsWith(".html") && !idsOf(target).has(decodeURIComponent(hash))) {
      problems.push(`${page}: ${attr}="${url}" → no element with id="${hash}"`);
    }
  }
}

if (problems.length) {
  console.error(`check-links: ${problems.length} broken link(s) in ${htmlFiles.length} pages:\n`);
  for (const p of [...new Set(problems)]) console.error("  " + p);
  process.exit(1);
}
console.log(`check-links: ${checked} internal links across ${htmlFiles.length} pages, all OK`);
